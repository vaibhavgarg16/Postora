import { describe, expect, it } from "vitest"
import { buildStarterStrategy } from "./strategy"

describe("starter strategy", () => {
  it("does not describe itself as an AI generation", () => {
    const result = buildStarterStrategy({
      businessName: "Mina's Kitchen",
      category: "Restaurant",
      description: "A small lunch counter in Jaipur.",
      targetAudience: "Office workers within two kilometres",
      brandTone: "Friendly",
      platforms: ["instagram"],
    })
    expect(result.source).toBe("STARTER")
    expect(result.outline).toContain("not an AI generation")
    expect(result.outline.toLowerCase()).not.toContain("generated by ai")
  })
})
